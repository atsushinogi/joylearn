'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const core = require('../core.js');
const base = path.resolve(__dirname, '..');
const courses = [
  { id: 'jujutsu-kaisen', title: '呪術廻戦', shortTitle: '呪術廻戦', subtitle: '呪術師たちの物語で学ぼう', cover: 'q001', theme: 'violet' },
  { id: 'my-hero-academia', title: '僕のヒーローアカデミア', shortTitle: 'ヒロアカ', subtitle: 'ヒーローたちの物語で学ぼう', cover: 'q002', theme: 'green' }
].map(meta => {
  const book = JSON.parse(fs.readFileSync(path.join(base, meta.id, 'workbook.json'), 'utf8'));
  if (book.questions.length !== 53) throw new Error(`${meta.id}: 全53問が必要です。`);
  const questions = book.questions.map((q, i) => {
    const image = `${meta.id}/exports/v1/webp/${q.id}.webp`;
    if (!fs.existsSync(path.join(base, image))) throw new Error(`画像がありません: ${image}`);
    return core.compileQuestion({ ...q, number: i + 1 }, image);
  });
  if (new Set(questions.map(q => q.id)).size !== 53) throw new Error('問題IDが重複しています。');
  const revision = crypto.createHash('sha256').update(JSON.stringify(questions)).digest('hex');
  return { ...meta, cover: `${meta.id}/exports/v1/webp/${meta.cover}.webp`, revision, questions };
});
fs.writeFileSync(path.join(base, 'question-bank.js'), '// Generated by scripts/build-app-data.cjs. Edit the workbooks, then rebuild.\nglobalThis.KANJI_STORY_BANK = ' + JSON.stringify({ version: 1, courses }, null, 2) + ';\n');
console.log(`教材データを生成しました: ${courses.map(c => `${c.shortTitle} ${c.questions.length}問`).join(' / ')}`);
